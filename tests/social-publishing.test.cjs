const assert = require('node:assert/strict');
const { issues, sharedIssues, mediaIssues, deliveryLocked, operationStatus, bindDialog, syncSocialUrls } = require('../plugin/fisar-cdj-core/assets/js/social-editor.js');
const facebook = { label: 'Facebook', images: 10, characters: 63206 };
const instagram = { label: 'Instagram', images: 10, characters: 2200 };
const row = (count, text = 'Un racconto con le nostre foto') => ({ text, images: Array.from({ length: count }, (_, i) => i + 1) });
assert.deepEqual(issues(row(10), facebook), []);
assert.match(issues(row(11), facebook)[0], /11 foto.*10/);
assert.match(issues(row(11), facebook)[0], /nessuna foto.*automaticamente/);
assert.deepEqual(issues(row(10), instagram), []);
assert.match(issues(row(11), instagram)[0], /11 foto.*10/);
assert.match(issues(row(0), instagram)[0], /almeno una foto/);
assert.deepEqual(issues(row(0), facebook), []);
assert.deepEqual(issues(row(1, '🍷'.repeat(2200)), instagram), []);
assert.match(issues(row(1, '🍷'.repeat(2201)), instagram)[0], /limite/);
assert.match(issues(row(1, '  '), instagram)[0], /Inserisci/);
const shared = { ...row(12), networks: { facebook: true, instagram: true } };
assert.match(sharedIssues(shared, { facebook, instagram })[0], /Facebook.*12 foto/);
shared.networks.facebook = false;
assert.match(sharedIssues(shared, { facebook, instagram })[0], /Instagram.*12 foto.*10/);
shared.networks.instagram = false;
assert.deepEqual(sharedIssues(shared, { facebook, instagram }), ['Seleziona almeno un social.']);
shared.networks.facebook = shared.networks.instagram = true;
shared.text = '  ';
assert.equal(sharedIssues(shared, { facebook, instagram }).filter((message) => message === 'Inserisci il testo del post.').length, 1);
for (const status of ['sent', 'scheduled', 'sending', 'error']) assert.equal(deliveryLocked({ id: 'remote-id', status }), true);
assert.equal(deliveryLocked({ status: 'unknown' }), true);
assert.equal(deliveryLocked({ status: 'rejected' }), false);
assert.equal(deliveryLocked(undefined), false);
assert.match(operationStatus('send', true, 'now').label, /Pubblicazione in corso/);
assert.match(operationStatus('send', true, 'scheduled').label, /Programmazione in corso/);
assert.match(operationStatus('send', false, 'now').label, /Simulazione in corso/);
for (const intent of ['save', 'refresh', 'reread']) {
	assert.ok(operationStatus(intent, true, 'now').message);
	assert.doesNotMatch(operationStatus(intent, true, 'now').message, /Pubblicato|Pubblicazione in corso/);
}
const photoVariants = [{ id: 1, variants: { facebook: { error: '' }, instagram: { error: 'Generazione non riuscita' } } }];
const photoPost = { ...row(1), networks: { facebook: true, instagram: false } };
assert.deepEqual(mediaIssues(photoPost, { facebook, instagram }, photoVariants), [], 'An unselected network cannot block the selected one.');
photoPost.networks.instagram = true;
assert.deepEqual(mediaIssues(photoPost, { facebook, instagram }, photoVariants), ['Instagram: Generazione non riuscita'], 'Errors in either selected network block send, regardless of which preview is shown.');
assert.equal(mediaIssues(photoPost, { facebook, instagram }, []).length, 2, 'Both selected networks require a prepared variant.');
function control() {
	const listeners = new Map();
	return { focused: 0, addEventListener(type, callback) { listeners.set(type, callback); }, emit(type, event = {}) { listeners.get(type)?.(event); }, focus() { this.focused++; } };
}
const dialog = control(), opener = control(), closer = control(), title = control();
let busy = false, opened = 0, closed = 0;
dialog.open = false;
dialog.showModal = () => { dialog.open = true; };
dialog.close = () => { dialog.open = false; dialog.emit('close'); };
bindDialog({ dialog, opener, closer, title, isBusy: () => busy, onOpen: () => opened++, onClose: () => closed++ });
assert.equal(opened, 0, 'Preparing the editor does not open or load the social composer.');
opener.emit('click');
assert.equal(dialog.open, true);
assert.equal(opened, 1);
assert.equal(title.focused, 1);
opener.emit('click');
assert.equal(opened, 1, 'Repeated clicks do not duplicate initialization.');
busy = true;
closer.emit('click');
assert.equal(dialog.open, true, 'An active send cannot be hidden by closing.');
let prevented = false;
dialog.emit('cancel', { preventDefault() { prevented = true; } });
assert.equal(prevented, true, 'Escape is prevented while sending.');
busy = false;
closer.emit('click');
assert.equal(dialog.open, false);
assert.equal(closed, 1);
assert.equal(opener.focused, 1, 'Closing returns focus to the launcher.');
opener.emit('click');
assert.equal(opened, 2, 'Reopening continues the existing preparation.');
const fbKey = '_fisar_report_facebook_url', igKey = '_fisar_report_instagram_url';
const urlFields = { [fbKey]: { value: '' }, [igKey]: { value: 'https://www.instagram.com/p/manual-unsaved/' } };
const originalUrls = { [fbKey]: { value: '' }, [igKey]: { value: '' } };
const urlDocument = { getElementById: (id) => urlFields[id], querySelector: (selector) => originalUrls[selector.includes(fbKey) ? fbKey : igKey] };
syncSocialUrls({ [fbKey]: 'https://www.facebook.com/posts/published', [igKey]: 'https://www.instagram.com/p/remote/' }, urlDocument);
assert.equal(urlFields[fbKey].value, 'https://www.facebook.com/posts/published');
assert.equal(originalUrls[fbKey].value, urlFields[fbKey].value, 'Automatic links update the form baseline too.');
assert.equal(urlFields[igKey].value, 'https://www.instagram.com/p/manual-unsaved/', 'Manual edits in progress are preserved.');
syncSocialUrls(undefined, urlDocument);
syncSocialUrls({ unexpected: 'ignored' }, { getElementById: () => { throw new Error('Unexpected field access.'); } });
console.log('Social composer: network-specific photo limits, no truncation, Unicode text and duplicate/uncertain delivery locks passed.');
console.log('Social dialog: lazy opening, focus return, busy/escape protection, reopening passed.');

