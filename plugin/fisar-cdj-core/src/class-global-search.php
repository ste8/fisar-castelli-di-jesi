<?php
/** Public search across site content, with explicit exclusions for pages under review. */
final class Fisar_CDJ_Global_Search {
	private const MARKER = 'fisar_cdj_global_search';
	private const TYPES = array( 'eventi' => 'fisar_evento', 'blog' => 'post', 'corsi' => 'fisar_corso', 'pagine' => 'page' );
	private const LOCATION_KEYS = array(
		'fisar_evento' => array( '_fisar_event_city', '_fisar_event_venue', '_fisar_event_address', '_fisar_event_province' ),
		'fisar_corso' => array( '_fisar_course_city', '_fisar_course_venue', '_fisar_course_address', '_fisar_course_province' ),
	);

	public static function init(): void {
		add_filter( 'query_vars', array( self::class, 'query_vars' ) );
		add_action( 'pre_get_posts', array( self::class, 'prepare_query' ), 20 );
		add_filter( 'posts_search', array( self::class, 'search' ), 20, 2 );
		add_filter( 'posts_orderby', array( self::class, 'order' ), 20, 2 );
	}

	public static function query_vars( array $vars ): array {
		$vars[] = 'tipo';
		return $vars;
	}

	public static function types(): array {
		return array( '' => 'Tutti', 'eventi' => 'Eventi', 'blog' => 'Blog', 'corsi' => 'Corsi', 'pagine' => 'Pagine' );
	}

	/** Published for direct review, but deliberately absent from the site's entry points. */
	public static function excluded_page_paths(): array {
		return apply_filters( 'fisar_cdj_search_excluded_page_paths', array( 'servizi', 'diventare-sommelier' ) );
	}

	/** Public information generated by the Contacts template, without copying names into the page. */
	public static function page_extra_text( WP_Post $page ): string {
		$text = '';
		if ( 'contatti' === $page->post_name ) {
			$details = fisar_cdj_get_delegation_details();
			$text = 'Il Delegato: ' . $details['delegate_name'] . '. Cellulare: ' . $details['delegate_phone']
				. '. Responsabile Servizi: ' . $details['services_name'] . '. ' . $details['services_email'] . '. '
				. implode( ' ', array_map( static fn ( $value ) => is_array( $value ) ? implode( ' ', $value ) : $value, $details ) );
		}
		return (string) apply_filters( 'fisar_cdj_search_page_extra_text', $text, $page );
	}

	/** Plain searchable copy also serves as the result excerpt for generated pages. */
	public static function page_text( WP_Post $page ): string {
		$body = preg_replace( '~</(?:p|h[1-6]|li|div|section|ul|ol)>~i', ' ', strip_shortcodes( $page->post_content ) );
		return trim( wp_strip_all_tags( $body ) . ' ' . self::page_extra_text( $page ) );
	}

	private static function normalized_text( string $text ): string {
		$text = remove_accents( wp_strip_all_tags( $text ) );
		$text = function_exists( 'mb_strtolower' ) ? mb_strtolower( $text ) : strtolower( $text );
		return trim( preg_replace( '/\s+/u', ' ', $text ) );
	}

	/** Only supplementary copy needs a small in-memory lookup; native page text stays in SQL. */
	private static function page_supplements(): array {
		$pages = get_posts( array( 'post_type' => 'page', 'post_status' => 'publish', 'has_password' => false, 'posts_per_page' => -1, 'orderby' => 'ID', 'order' => 'ASC' ) );
		$texts = array();
		foreach ( $pages as $page ) {
			$text = self::normalized_text( self::page_extra_text( $page ) );
			if ( '' !== $text ) { $texts[ $page->ID ] = $text; }
		}
		return $texts;
	}

	public static function state( WP_Query $query ): array {
		$text = $query->get( 's' );
		$text = is_string( $text ) ? trim( sanitize_text_field( $text ) ) : '';
		$type = $query->get( 'tipo' );
		return array(
			'text' => function_exists( 'mb_substr' ) ? mb_substr( $text, 0, 200 ) : substr( $text, 0, 200 ),
			'type' => is_string( $type ) && isset( self::TYPES[ $type ] ) ? $type : '',
		);
	}

	public static function url( string $text = '', string $type = '' ): string {
		$args = array( 's' => $text );
		if ( isset( self::TYPES[ $type ] ) ) { $args['tipo'] = $type; }
		return add_query_arg( $args, home_url( '/' ) );
	}

	public static function prepare_query( WP_Query $query ): void {
		if ( is_admin() || ! $query->is_main_query() || ! $query->is_search() || $query->is_feed() ) { return; }
		$state = self::state( $query );
		$query->set( self::MARKER, true );
		$query->set( 's', $state['text'] );
		$query->set( 'tipo', $state['type'] );
		$query->set( 'post_type', $state['type'] ? self::TYPES[ $state['type'] ] : array_values( self::TYPES ) );
		$excluded = (array) $query->get( 'post__not_in', array() );
		foreach ( self::excluded_page_paths() as $path ) {
			$page = get_page_by_path( $path );
			if ( $page ) { $excluded[] = $page->ID; }
		}
		$query->set( 'post__not_in', array_unique( array_map( 'intval', $excluded ) ) );
		$query->set( 'post_status', 'publish' );
		$query->set( 'has_password', false );
		$query->set( 'posts_per_page', 12 );
		$query->set( 'search_columns', array( 'post_title', 'post_content' ) );
		$query->set( 'orderby', 'relevance' );
		$query->set( 'ignore_sticky_posts', true );
		// Opening or resetting the search must not list the entire site.
		if ( '' === $state['text'] ) { $query->set( 'post__in', array( 0 ) ); }
	}

	/** Each native search term may match text or a documented public location. */
	public static function search( string $search, WP_Query $query ): string {
		if ( ! $query->get( self::MARKER ) || ! $query->get( 's' ) ) { return $search; }
		global $wpdb;
		$clauses = array();
		$page_texts = in_array( 'page', (array) $query->get( 'post_type' ), true ) ? self::page_supplements() : array();
		$prefix = apply_filters( 'wp_query_search_exclusion_prefix', '-' );
		foreach ( (array) $query->get( 'search_terms' ) as $term ) {
			$exclude = $prefix && str_starts_with( $term, $prefix );
			if ( $exclude ) { $term = substr( $term, strlen( $prefix ) ); }
			$like = '%' . $wpdb->esc_like( $term ) . '%';
			$matches = array( $wpdb->prepare( "({$wpdb->posts}.post_title LIKE %s OR {$wpdb->posts}.post_content LIKE %s)", $like, $like ) );
			foreach ( self::LOCATION_KEYS as $type => $keys ) {
				$placeholders = implode( ', ', array_fill( 0, count( $keys ), '%s' ) );
				$matches[] = $wpdb->prepare(
					"({$wpdb->posts}.post_type = %s AND EXISTS (SELECT 1 FROM {$wpdb->postmeta} search_location WHERE search_location.post_id = {$wpdb->posts}.ID AND search_location.meta_key IN ({$placeholders}) AND search_location.meta_value LIKE %s))",
				array_merge( array( $type ), $keys, array( $like ) )
				);
			}
			$page_ids = array();
			foreach ( $page_texts as $id => $text ) {
				if ( str_contains( $text, self::normalized_text( $term ) ) ) { $page_ids[] = (int) $id; }
			}
			if ( $page_ids ) { $matches[] = $wpdb->posts . '.ID IN (' . implode( ',', $page_ids ) . ')'; }
			$clauses[] = ( $exclude ? 'NOT ' : '' ) . '(' . implode( ' OR ', $matches ) . ')';
		}
		return $clauses ? ' AND (' . implode( ' AND ', $clauses ) . ')' : $search;
	}

	public static function order( string $order, WP_Query $query ): string {
		if ( ! $query->get( self::MARKER ) ) { return $order; }
		global $wpdb;
		return ( $order ? $order . ', ' : '' ) . "{$wpdb->posts}.post_date DESC, {$wpdb->posts}.ID DESC";
	}
}
